## Q001. 系统设计面试中如何澄清需求？

**回答：**

系统设计面试的第一关不是画架构图，而是澄清需求。Alex Xu 在 _System Design Interview_ 里反复强调：**"Giving out an answer quickly does not give you bonus points."** 面试题故意开放，就是为了看你能不能先问对问题，再设计方案。

我会用一个四步框架来组织需求澄清：

**第一步：功能范围。** 先搞清楚系统到底要做什么。问清楚核心功能是什么，哪些是 nice-to-have，哪些明确不做。比如设计短链接系统，核心是"给定长 URL 返回短码"和"给定短码重定向到长 URL"。要不要自定义短码？要不要过期时间？要不要统计点击量？要不要 API？这些会直接影响架构复杂度。如果面试官说"先做核心"，就不要一上来就设计分析平台。

**第二步：用户和规模。** 这是估算的基础。DAU 多少？读多还是写多？流量是均匀的还是突发性的？比如短链接系统，读写比可能是 100:1，这意味着缓存是核心；如果是日志采集系统，写远大于读，那写入吞吐和存储才是重点。不要假设规模——直接问。

**第三步：非功能需求。** 延迟要求（p99 是多少？）、可用性要求（几个 9？）、一致性要求（强一致还是最终一致？）、持久性要求（数据能丢吗？）。这些决定了技术选型的天花板。比如要求 p99 < 10ms 的读操作，就不能走"查 DB 再返回"的路径，必须上缓存；要求 99.99% 可用性，就必须多 AZ 部署。

**第四步：约束和假设。** 现有技术栈是什么？团队能力如何？时间线多紧？预算有没有上限？是否需要兼容现有系统？这些工程约束往往比纯技术因素更能决定最终方案。

一个容易被忽略的点是：**把假设写下来并确认。** 比如"我假设 DAU 是 100M，读写比 100:1，每条数据平均 1KB，保留 5 年。这些假设合理吗？"这样面试官可以纠正你，而不是等你画完架构图才发现方向错了。

常见错误：
- 一上来就说"用 Kafka + Redis + PostgreSQL + Kubernetes"，没澄清需求就堆组件
- 假设规模而不确认，比如默认是"百万用户"但面试官想的是"十亿用户"
- 跳过边界条件，比如没问"短链接要不要支持删除/更新"
- 不问非功能需求就开始设计，最后发现延迟要求根本达不到

面试里可以这样开场：

```
在开始设计之前，我想先澄清几个方面：第一，系统的核心功能是什么，哪些是 V1 必须做的，哪些可以后续迭代？第二，预期的用户规模和流量特征是怎样的——DAU、读写比、峰值因子？第三，对延迟、可用性、一致性和持久性有什么具体要求？第四，有没有技术栈、团队或时间线的约束？
```

## Q002. 功能需求和非功能需求分别如何拆解？

**回答：**

功能需求（Functional Requirements）回答"系统做什么"，非功能需求（Non-Functional Requirements, NFRs）回答"系统做得怎么样"。面试里两个都要拆，但 NFRs 往往被忽略，而它恰恰决定了架构的上限。

**功能需求拆解：**

我会按用户旅程拆。以短链接系统为例：

1. **创建短链接**：用户提交长 URL，系统返回短码。要不要支持自定义短码？要不要设置过期时间？要不要一次性链接？
2. **重定向**：用户访问短链接，系统 302 重定向到长 URL。要不要区分 301 和 302？
3. **查询/管理**：用户能不能查看自己创建的所有短链接？能不能删除？能不能修改目标 URL？
4. **可选功能**：点击统计、API 访问、批量创建、访问控制。

拆解技巧：每个功能问三个问题——"谁用？""输入什么？""输出什么？"然后判断它是核心路径还是增值功能。核心路径先做，增值功能可以异步或后续迭代。

**非功能需求拆解：**

NFRs 建议用 ISO 25010 的维度来拆，但面试里不需要背标准，记住这几个关键维度就够了：

1. **性能**：延迟（p50/p95/p99）和吞吐（QPS）。短链接重定向要求 p99 < 10ms 和 100:1 读写比下的 36K QPS，这直接决定了缓存是核心组件。
2. **可用性**：系统能正常服务的时间比例。99.9%（三个九）意味着年宕机不超过 8.76 小时；99.99%（四个九）是 52 分钟。每多一个九，工程成本大约翻 10 倍。
3. **可扩展性**：系统如何应对增长。是加机器（横向扩展）还是换更大的机器（纵向扩展）？数据量增长时查询性能会不会退化？
4. **一致性**：强一致还是最终一致？短链接的创建可以最终一致（短暂时间内查不到新链接可接受），但库存扣减必须是强一致。
5. **持久性**：数据写入后会不会丢？复制因子是多少？是否需要跨 AZ/Region 备份？
6. **安全性**：认证、授权、加密、审计。短链接要不要防止枚举？要不要防止恶意链接？
7. **可维护性**：部署、监控、告警、回滚是否方便？配置是否集中管理？

**NFR 之间的 trade-off 是面试高分区：**

| 需求 | 优化手段 | 代价 |
|------|---------|------|
| 低延迟 | 缓存、CDN | 数据可能不一致，成本增加 |
| 高可用 | 多 AZ、冗余部署 | 成本翻倍，复杂度增加 |
| 强一致 | 分布式共识（Raft/Paxos） | 吞吐降低，延迟增加 |
| 高持久 | 多副本（RF=3） | 3 倍存储成本 |

面试里要主动说 trade-off。比如"为了 p99 < 10ms，我选择 Redis 缓存 + CDN，代价是短链接创建后可能有几百毫秒的缓存不一致窗口，这对短链接场景是可接受的。"

常见错误：
- 只列功能需求，不提 NFRs
- 把 NFRs 当成"附加题"而不是"决定架构的核心输入"
- 不讨论 trade-off，好像所有 NFRs 都能同时最优

## Q003. 如何估算 QPS、存储、带宽和连接数？

**回答：**

Back-of-envelope（信封背面）估算是系统设计面试的基本功。Jeff Dean 说过，在动手构建系统之前，应该先用 BOTE 计算评估设计是否可行。核心公式不复杂，但要知道每个参数从哪里来、调整因子怎么取。

**QPS 估算：**

```
平均 QPS = DAU x 每人每天请求数 / 86400
峰值 QPS = 平均 QPS x 峰值因子（通常 2-10x）
```

以短链接系统为例，假设 DAU 100M，每人每天创建 1 条、访问 10 条：

```
写 QPS = 100M x 1 / 86400 = 1157 = 1.2K
读 QPS = 100M x 10 / 86400 = 11574 = 12K
峰值读 QPS = 12K x 3 = 36K
```

峰值因子的取值很关键。Google SRE Workbook 建议根据业务特征选择：
- 企业内部 SaaS：1.5-2x
- 社交媒体（日间波动）：2-5x
- 秒杀/赛事直播：10-100x
- 病毒传播：100-1000x

**存储估算：**

```
日存储 = 日事件数 x 单条平均大小
年存储 = 日存储 x 365
N 年总存储 = 年存储 x N x 复制因子 x 元数据/索引膨胀系数
```

以短链接为例，假设每天创建 100M 条，每条记录约 1KB：

```
日存储 = 100M x 1KB = 100 GB
年存储 = 100 GB x 365 = 36.5 TB
5 年存储 = 36.5 TB x 5 x 3（复制因子）x 1.5（索引开销）= 821 TB
```

复制因子通常取 3（Dynamo 论文、HDFS、Cassandra 的默认值）。索引和元数据开销通常加 30%-50%。如果用了 Elasticsearch 做全文索引，存储膨胀可能到 3-10x。

**带宽估算：**

```
入站带宽 = 日写入量 / 86400
出站带宽 = 入站带宽 x 读写比
```

短链接场景：入站带宽约 9.3 Mbps，出站带宽约 93 Mbps。

**连接数估算：**

```
DB 连接数 = 应用实例数 x 每实例连接池大小（通常 10-50）
```

假设 13 个应用实例，每实例 20 个 DB 连接：260 个 DB 连接。PostgreSQL 默认 max_connections = 100，需要调大或用 PgBouncer 做连接池。

**关键参考数字（Jeff Dean, 2019）：**

| 操作 | 时间 | 类比（1ns=1s） |
|------|------|---------------|
| L1 cache | 0.5 ns | 0.5s |
| 主存读取 | 100 ns | 100s |
| 同数据中心往返 | 500,000 ns | 5.8 天 |
| 磁盘寻道 | 10,000,000 ns | 4 个月 |
| 跨大西洋网络包 | 150,000,000 ns | 5 年 |

这些数字的价值在于快速判断瓶颈：一次磁盘寻道（10ms）可以执行 1000 万次 L1 cache 访问。如果设计里每次请求都做磁盘随机读，那延迟一定很高。

常见错误：
- 用平均 QPS 而不是峰值 QPS 做容量规划
- 忘记乘复制因子和索引膨胀系数
- 忽略连接池上限（PostgreSQL 默认 100 连接是常见坑）
- 把带宽和吞吐混为一谈（带宽是 bit/s，吞吐是 request/s）

面试里可以这样说：

```
我先做一轮 BOTE 估算。假设 DAU 100M，读写比 100:1，峰值因子 3x。写 QPS 约 1.2K，峰值读 QPS 约 36K。日存储 100GB，5 年约 821TB（含 3 副本和索引）。出站带宽约 93Mbps。这些数字告诉我：读路径必须走缓存，存储需要分片，单机 DB 连接数需要关注。
```

## Q004. 如何从 QPS 推导实例数量？

**回答：**

从 QPS 推导实例数量，核心公式是：

```
实例数 = 峰值 QPS / (单实例 QPS x 目标利用率)
```

三个变量，每个都要认真取。

**单实例 QPS 的估算：**

这取决于服务类型。没有万能数字，但可以参考经验范围：

| 服务类型 | 单核 QPS | 16 核服务器 QPS |
|---------|---------|----------------|
| 纯内存 API（无 DB） | 5,000-10,000 | 40,000-80,000 |
| API + Redis 缓存 | 2,000-5,000 | 16,000-40,000 |
| API + DB 查询 | 500-2,000 | 4,000-16,000 |
| 重计算（ML 推理等） | 50-500 | 400-4,000 |

面试里如果面试官没给具体数字，可以取保守值。比如短链接重定向服务（纯内存 + Redis），取 5,000 QPS/实例。

**目标利用率：**

不要跑满。根据排队论（Little's Law），利用率接近 100% 时延迟趋于无穷：

```
队列深度 = 利用率 / (1 - 利用率)
利用率 50% -> 队列深度 1
利用率 80% -> 队列深度 4
利用率 90% -> 队列深度 9
利用率 95% -> 队列深度 19
```

"拐点"在 60%-80%。通常取 60%-70% 作为目标利用率，留出应对突发和单机故障的余量。

**N+2 冗余（Google SRE）：**

Google SRE Book 的建议是：如果你需要 N 个实例处理峰值流量，就部署 N+2 个。这样一台机器做计划内升级、另一台意外故障时，系统仍然有 N 台在服务。不会因为"升级 + 故障"同时发生而容量不足。

**完整示例（短链接系统）：**

```
峰值读 QPS = 36,000
单实例 QPS = 5,000（保守估计）
目标利用率 = 70%

基础实例数 = 36,000 / (5,000 x 0.7) = 10.3 -> 11 台
加 N+2 冗余 = 13 台
```

**反过来验证连接数：**

```
13 台 x 20 连接/台 = 260 个 DB 连接
PostgreSQL 默认 max_connections = 100 -> 需要调大或用连接池
```

如果 260 个连接对 DB 压力太大，有两个方向：一是加 PgBouncer 做连接池复用；二是提高单实例 QPS（优化代码、加本地缓存），减少实例数。

**纵向扩展 vs 横向扩展的决策：**

从 QPS 推导实例数时，还要考虑纵向扩展是否更合适。如果算出来只需要 2-3 台，用更大的机器（纵向扩展）可能比加机器（横向扩展）更简单。但当实例数超过一定阈值（比如 10 台以上），横向扩展的优势（无单点、弹性伸缩、零停机扩容）就超过了纵向扩展。

常见错误：
- 用平均 QPS 而不是峰值 QPS 计算
- 不乘利用率因子，假设单实例能跑满标称 QPS
- 不考虑 N+2 冗余，升级时容量不够
- 算完实例数不验证 DB 连接数、网络带宽等下游瓶颈

面试里可以这样答：

```
我从峰值 QPS 推导实例数。假设峰值 36K QPS，单实例保守估计 5K QPS，目标利用率 70%，需要 11 台。加 N+2 冗余后是 13 台。然后我会反向验证：13 台实例各 20 个 DB 连接 = 260 个连接，需要确认 DB 连接池是否够用，不够就加 PgBouncer 或提高单实例吞吐。
```

