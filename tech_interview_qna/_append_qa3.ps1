## Q009. 多可用区部署解决什么问题？

**回答：**

多可用区（Multi-AZ）部署解决的是**单个数据中心级别的故障**。一个可用区（Availability Zone）是一个或多个物理数据中心，拥有独立的供电、冷却和网络。同一 Region 内的 AZ 之间物理距离通常在几十公里以内，往返延迟（RTT）小于 2ms。

**多 AZ 解决的问题：**

| 故障类型 | 单 AZ 后果 | 多 AZ 效果 |
|---------|-----------|-----------|
| 单 AZ 断电 | 全站宕机 | 流量自动切换到其他 AZ |
| 冷却系统故障 | 服务器过热关机 | 其他 AZ 正常服务 |
| 网络设备故障 | 整个 AZ 不可达 | 负载均衡器摘除故障 AZ |
| 自然灾害（火灾/水灾） | 数据可能丢失 | 数据在其他 AZ 有副本 |
| 计划内维护 | 需要停机窗口 | 逐 AZ 滚动更新，零停机 |

**多 AZ 架构要点：**

1. **应用层**：至少 2 个 AZ 各部署一组实例，负载均衡器跨 AZ 分发流量。一个 AZ 故障时，负载均衡器自动把流量切到健康 AZ。
2. **数据库层**：
   - RDS Multi-AZ：同步 standby 在另一个 AZ，自动故障转移，约 1-2 分钟切换时间
   - Aurora：6 个副本跨 3 个 AZ，最多 15 个读副本跨 AZ
   - 自建数据库：Patroni + etcd 做自动故障转移
3. **缓存层**：Redis Cluster 跨 AZ 部署，每个分片的主从在不同 AZ
4. **消息队列**：Kafka 多 broker 跨 AZ，RF=3，min.insync.replicas=2

**多 AZ 的代价：**

| 代价 | 说明 |
|------|------|
| 跨 AZ 数据传输费 | AWS 等云厂商对跨 AZ 流量收费 |
| 资源冗余 | 至少 2x 实例，成本翻倍 |
| 应用改造 | 需要感知 AZ、处理故障切换 |
| 有状态服务延迟 | 跨 AZ 同步复制增加写入延迟（通常 < 2ms） |

**AWS Well-Architected 建议：**

"Deploy and operate all production workloads in at least two Availability Zones." 大多数工作负载在单个 Region 内使用多 AZ 就能达到 99.99% 的可用性目标。多 Region 只在需要 >99.99% 可用性或灾难恢复时才考虑。

常见错误：
- 部署了多 AZ 但没有测试故障切换，真故障时才发现切换脚本有问题
- 所有实例都在同一个 AZ 的同一个子网，以为"多子网"就是"多 AZ"
- 数据库主库在一个 AZ，从库也在同一个 AZ——AZ 故障时数据库完全不可用
- 负载均衡器只在一个 AZ——它自己成了 SPOF

面试里可以这样答：

```
多 AZ 解决单数据中心故障问题。我会确保应用实例、数据库、缓存、消息队列都跨 AZ 部署。应用层用跨 AZ 负载均衡，数据库用 Multi-AZ 同步复制，缓存用跨 AZ 的 Redis Cluster。代价是跨 AZ 流量费用和 2x 资源冗余，但对 99.99% 可用性目标是必需的。关键是要实际测试过故障切换，不能只靠配置。
```

## Q010. 多地域部署解决什么问题？

**回答：**

多地域（Multi-Region）部署解决的是**整个地理区域级别的故障**和**全球用户的延迟问题**。一个 Region 包含至少 3 个 AZ，Region 之间物理距离数百到数千公里，往返延迟 50-200ms。

**多 Region 解决的三大问题：**

1. **灾难恢复**：Region 级别故障（地震、区域网络中断、大规模供电故障）。多 AZ 无法解决 Region 级故障。
2. **全球低延迟**：用户从最近的 Region 获得服务。美东用户连美东 Region（~20ms），欧洲用户连欧洲 Region（~20ms），而不是都跨大洋连一个 Region（~150ms）。
3. **数据驻留合规**：某些国家/地区要求数据必须存储在本地。多 Region 可以满足 GDPR、数据主权等法规要求。

**多 Region 部署模式：**

| 模式 | 描述 | 复杂度 | RTO | RPO |
|------|------|--------|-----|-----|
| Active-Passive | 一个 Region 服务流量，另一个热备 | 中 | 分钟级 | 秒-分钟（异步复制） |
| Active-Active | 所有 Region 同时服务流量 | 高 | 秒级 | 秒级（需要冲突解决） |
| Pilot Light | 最小化备用，故障时扩容 | 低 | 小时级 | 分钟-小时 |
| Warm Standby | 缩量运行的副本在第二 Region | 中 | 分钟级 | 秒-分钟 |

**Active-Active 的核心挑战：**

| 挑战 | 解决方案 |
|------|---------|
| 跨 Region 数据复制 | DynamoDB Global Tables、Aurora Global Database、Cassandra 多 DC |
| 写冲突 | Last-Writer-Wins（LWW）、CRDT、应用层冲突解决 |
| 全球流量路由 | Route 53 延迟路由、Anycast DNS |
| 跨 Region 延迟 | 50-200ms RTT，需要异步处理 |
| 幂等性 | 每个操作必须可以安全重放 |

**多 AZ vs 多 Region 决策：**

| 因素 | 多 AZ | 多 Region |
|------|-------|----------|
| 最高可用性 | 99.99% | 99.999%+ |
| RTO（恢复时间） | 分钟 | 分钟到小时 |
| RPO（数据丢失） | 零（同步复制） | 秒到分钟（异步） |
| 成本 | 2-3x | 3-5x+ |
| 复杂度 | 低-中 | 高 |
| 用户延迟 | 区域内 | 全球 |

AWS 的官方建议："Multi-Region is most common for: regulatory requirements, disaster recovery with bounded RTO, and latency optimization for global users." 大多数工作负载不需要多 Region。

常见错误：
- 以为多 AZ 就能解决 Region 级灾难
- 没有实际演练过 Region 故障切换（切 DNS 容易，但数据一致性、状态同步、容量准备才是难点）
- Active-Active 没有处理好写冲突，两个 Region 同时修改同一条数据导致数据不一致
- 跨 Region 同步调用——50-200ms 的 RTT 会让用户体验极差

面试里可以这样答：

```
多 Region 解决 Region 级灾难恢复和全球低延迟。大多数系统用多 AZ 就够了，多 Region 只在需要 >99.99% 可用性、灾难恢复或全球低延迟时才考虑。Active-Passive 是性价比最高的模式：一个 Region 服务，另一个热备，数据异步复制。Active-Active 虽然恢复最快，但写冲突和跨 Region 一致性问题很复杂，需要 CRDT 或应用层冲突解决。
```

## Q011. 同步链路和异步链路如何选择？

**回答：**

同步（Synchronous）和异步（Asynchronous）的选择是系统设计里最常见的 trade-off 之一。选错方向会导致级联故障或数据不一致。

**核心区别：**

| 维度 | 同步 | 异步 |
|------|------|------|
| 阻塞 | 是（等待响应） | 否（立即返回） |
| 故障传播 | 级联（A 失败导致 B 也失败） | 隔离（B 失败被队列缓冲、重试） |
| 延迟 | 累加（100ms x 5 = 500ms） | 对调用者最小 |
| 缓冲 | 无 | 队列缓冲请求 |
| 扩缩容 | 困难（需要一起扩） | 容易（独立扩缩） |
| 一致性 | 强 | 最终 |

**选择同步的场景：**

- 需要立即决策的核心路径操作
- 认证鉴权（token 是否有效、用户是否存在）
- 支付处理（需要成功/失败响应）
- 库存检查（是否有货）
- 原则：一个请求链路中同步调用不超过 1-2 个

**选择异步的场景：**

- 邮件、短信通知（可以延迟）
- 数据分析、日志、指标采集（非阻塞）
- 报表生成、数据仓库更新（最终一致即可）
- 图片处理、文件转换（后台任务）
- Fan-out 模式（一个事件触发多个处理器）

**决策启发式：**

问自己一个问题：**"这个调用的响应，对于我给当前请求返回一个有意义的回复，是必需的吗？"**
- 是 -> 倾向同步（但要加熔断和超时）
- 否 -> 异步候选

**生产环境的铁律：**

1. **默认异步**。只有确实需要立即响应时才用同步。
2. **同步调用链不超过 2 层**。如果需要 A->B->C，重新设计。
3. **每个同步调用都要有熔断器（Circuit Breaker）和超时**。没有超时的同步调用是定时炸弹。
4. **每个异步消费者必须幂等**。消息可能被投递多次。
5. **死信队列（DLQ）**：重试耗尽后进入 DLQ，人工介入。
6. **如果两个服务总是一起部署、一起扩缩，它们就不该是独立的服务。**

**同步链路中的保护模式：**

| 模式 | 作用 | 实现 |
|------|------|------|
| 超时（Timeout） | 防止无限等待 | 每个调用设 timeout，通常 1-5s |
| 熔断（Circuit Breaker） | 快速失败，防止级联 | 错误率超阈值 -> 直接拒绝 -> 半开探测 |
| 舱壁（Bulkhead） | 隔离资源 | 不同下游用独立线程池/连接池 |
| 重试（Retry） | 处理临时故障 | 指数退避 + jitter，有最大次数 |

**异步链路的可靠性保证：**

- 消息持久化：先写消息队列，再返回成功（at-least-once）
- 消费者幂等：用 idempotency key 去重
- 死信队列：重试 N 次失败后进入 DLQ
- 顺序保证：同一实体的消息发到同一分区

常见错误：
- 把通知、日志、分析等非关键操作放在同步链路里，拖慢核心响应
- 同步调用不加超时，一个慢下游拖死所有请求线程
- 异步消费者不幂等，消息重复投递导致重复扣款/重复发邮件
- 以为"异步就是丢消息队列里不管了"，没有 DLQ 和监控

面试里可以这样答：

```
选择同步还是异步，核心问题是"这个响应对于当前请求是否必需"。支付、鉴权、库存检查需要同步；通知、日志、分析应该异步。同步链路要加超时、熔断、舱壁保护；异步链路要保证消息持久化、消费者幂等、有死信队列。默认倾向异步，同步调用链不超过 2 层。
```

## Q012. 核心链路和非核心链路如何隔离？

**回答：**

核心链路（Critical Path）是用户请求必须同步完成才能得到响应的操作序列。非核心链路是可以延迟、异步处理或失败不影响用户体验的操作。隔离的目标是：**非核心链路的故障不能拖垮核心链路。**

**核心链路识别：**

沿着用户旅程，每一步问："用户需要等这一步完成才能看到结果吗？"
- 电商下单：验证购物车 -> 锁定库存 -> 处理支付 -> 创建订单（核心）
- 电商下单：发确认邮件、更新推荐、写分析日志（非核心）

核心链路要尽可能短。每多一个同步依赖，就多一个故障点。

**隔离技术矩阵：**

| 技术 | 原理 | 示例 |
|------|------|------|
| 消息队列 | 非核心工作异步化 | 下单后通过 Kafka 异步发邮件 |
| 独立线程池 | 核心和非核心用不同线程池 | 结账线程池 vs 推荐线程池 |
| CQRS | 读写分离 | 分析查询走读副本，不影响写入 |
| 熔断器 | 保护核心链路不受下游故障影响 | 推荐服务挂了，熔断后跳过推荐 |
| 舱壁（Bulkhead） | 按路径隔离资源 | 支付服务独立连接池 |
| 降级 | 非核心功能故障时返回降级结果 | 推荐挂了返回热门商品 |

**电商下单的隔离示例：**

```
核心链路（同步，必须全部成功）：
  验证购物车 -> 锁定库存 -> 处理支付 -> 创建订单

非核心链路（异步，失败不影响下单）：
  订单创建后 -> Kafka -> 发确认邮件
                    -> 更新推荐模型
                    -> 写数据仓库
                    -> 发 Webhook 通知
```

**短链接系统的隔离示例：**

```
核心链路（同步，p99 < 10ms）：
  短码 -> Redis 查长 URL -> 302 重定向

非核心链路（异步）：
  重定向后 -> Kafka -> Flink 聚合点击 -> ClickHouse 分析
```

**Anti-Pattern：核心链路污染**

把非核心操作加到核心链路里。症状：
- p99 延迟很高（被非核心操作拖慢）
- 非核心服务故障导致核心功能不可用（比如推荐服务挂了导致下单失败）
- 加机器不能线性提升吞吐（非核心操作成为瓶颈）

**隔离的资源维度：**

| 资源 | 核心链路 | 非核心链路 |
|------|---------|-----------|
| 线程池 | 独立、高优先级 | 独立、低优先级、有上限 |
| 连接池 | 独立、保证最小连接数 | 独立、有最大连接数限制 |
| 超时 | 严格（1-5s） | 宽松（10-30s） |
| 重试 | 谨慎（最多 1-2 次） | 可多次（指数退避） |
| 熔断 | 激进（快速失败） | 保守 |

常见错误：
- 把发邮件、写日志、更新分析放在同步链路里
- 核心和非核心共享线程池/连接池，非核心耗尽资源导致核心不可用
- 降级逻辑不测试，真故障时降级代码本身报错

面试里可以这样答：

```
核心链路是用户必须等待的操作，要尽可能短。非核心操作通过消息队列异步化，用独立线程池和连接池隔离。核心链路加严格超时和熔断，非核心链路故障时降级（比如推荐挂了返回热门商品）。关键是不要让非核心故障拖垮核心——电商下单不能因为推荐服务挂了而失败。
```

