## Q013. 读多写少和写多读少系统设计有什么差异？

**回答：**

读写比例是系统设计里最基础也最重要的输入参数之一。它直接决定了缓存策略、数据库选型、索引设计和扩缩容方案。

**核心差异一览：**

| 维度 | 读多写少 | 写多读少 |
|------|---------|---------|
| 读写比 | 100:1 到 1000:1 | 1:1 到 1:10 |
| 主要瓶颈 | 数据检索延迟 | 数据写入吞吐 |
| 典型场景 | 社交信息流、商品目录、新闻 | 日志采集、IoT 遥测、埋点分析 |
| 核心优化 | 缓存 + 读副本 | 分区 + 追加写 |
| 数据库倾向 | 关系型 + 读副本 | LSM 引擎（Cassandra、RocksDB） |

**读多写少优化策略：**

| 策略 | 原理 | 效果 |
|------|------|------|
| 缓存（Redis、CDN） | 热点数据放内存 | 吸收 80-95% 读流量 |
| 读副本 | 读走副本，写走主库 | 读横向扩展 |
| 索引 | 常用查询字段建索引 | 查询加速（但拖慢写入） |
| 反范式化 | 预 JOIN 数据，读优化视图 | 读更快，冗余存储 |
| 物化视图 | 预计算复杂查询 | 即时查询结果 |
| CDN | 静态内容边缘分发 | 减少源站压力 |

**写多读少优化策略：**

| 策略 | 原理 | 效果 |
|------|------|------|
| 追加写（Append-Only） | 顺序写，不原地更新 | 10x 写入吞吐 |
| 批量写入 | 多条合并为一批 | 减少单条写入开销 |
| 异步写入 | 先入队列，后台写 | 不阻塞调用方 |
| 分片（Sharding） | 写入分散到多个分区 | 线性扩展写入能力 |
| LSM Tree | 顺序写 + 后台合并（Cassandra、RocksDB） | 高写入吞吐 |
| WAL（Write-Ahead Log） | 先写日志，异步刷盘 | 持久且快 |

**CQRS（命令查询职责分离）：**

当读写差异大到无法用同一套模型优化时，CQRS 是自然选择：

| 关注点 | 写端（Command） | 读端（Query） |
|--------|---------------|--------------|
| 数据模型 | 规范化（3NF） | 反范式化（读优化） |
| 数据库类型 | 关系型（ACID） | 文档型或搜索引擎 |
| 扩缩容 | 按实体 ID 分片 | 广泛复制 |
| 一致性 | 强一致 | 最终一致 |

**根本矛盾：**

- **读想要**：缓存、副本、最终一致性、反范式化
- **写想要**：协调、串行化、确认、规范化

优化一个方向通常会损害另一个。面试里要明确说出你的取舍。

**选型建议：**

- 读多写少（>10:1）：Redis + 读副本 + CDN 是标配。数据库用 PostgreSQL/MySQL，加索引和物化视图。
- 写多读少（<1:1）：考虑 LSM 引擎（Cassandra、ScyllaDB、RocksDB），用分片和批量写入提升吞吐。用 Kafka 做写入缓冲。
- 极端读写分离：CQRS + Event Sourcing，写端用关系型 DB，读端用 Elasticsearch 或 ClickHouse。

常见错误：
- 读写比 100:1 的系统不加缓存，每次请求都查 DB
- 写多读少的系统用 B-Tree 数据库（如 MySQL），写入瓶颈严重
- 读写都用同一套 schema，不区分读优化和写优化
- 过度设计：读写比 2:1 的系统没必要上 CQRS

面试里可以这样答：

```
读写比决定优化方向。读多写少（>10:1）核心是缓存 + 读副本 + CDN；写多读少（<1:1）核心是分片 + 追加写 + LSM 引擎。极端场景用 CQRS 分离读写模型。关键是要根据实际读写比做取舍，不要过度设计——读写比 2:1 的系统不需要 CQRS。
```

## Q014. 如何设计热点保护？

**回答：**

热点（Hotspot / Hot Partition）是指某个数据分片或 key 承受了远超平均水平的流量，导致局部过载。热点保护的核心思路是：**分散流量、缓存热点、隔离影响。**

**热点的根因：**

| 根因 | 示例 | 缓解方向 |
|------|------|---------|
| 名人/病毒 key | 明星微博、爆款商品 | 缓存 + 混合 fan-out |
| 时间相关 key | 所有写入打到"今天"的分区 | 复合 key 加 shard 后缀 |
| 低基数 key | 性别（M/F）、状态枚举 | 重新设计分区键 |
| 突发流量 | 突发新闻、秒杀 | 自适应容量 + 缓存 |
| 写热点 key | 秒杀中单个商品的库存扣减 | 写分片 |

**缓解策略：**

**1. 缓存（对付读热点）**

在热点分区前放缓存。95% 缓存命中率 = 95% 的流量不碰 DB。多级缓存（本地 LRU + Redis + CDN）逐层吸收流量。注意缓存雪崩和缓存击穿——热点 key 过期瞬间，大量请求穿透到 DB。

**2. 写分片（对付写热点）**

给分区键加随机后缀（如 `user_id + random(0-99)`），写入分散到 100 个分片。读取时需要 scatter-gather（查所有分片后合并）。代价是读复杂度增加，适合写远大于读的场景。

**3. 混合 Fan-Out（Twitter 模式）**

- 普通用户（<1M 粉丝）：fan-out on write，发推时预计算推送到粉丝时间线
- 大 V 用户（>1M 粉丝）：fan-out on read，粉丝拉取时实时合并大 V 推文

这个模式把热点用户的写入压力转化为了读取时的可控合并操作。

**4. 一致性哈希 + 虚拟节点**

物理节点映射到多个虚拟节点，热点 key 被分散到多个物理节点。节点增减时数据重分布最小。

**5. 自适应容量**

监控每个分片的负载，动态将热分片的数据迁移到更多节点，或给热分片分配更多资源。

**热点检测：**

- p50 vs p99 延迟差异：如果 p99 是 p50 的 10 倍以上，大概率有热点分片
- 按分片/节点的 QPS 和延迟分布：个别节点 QPS 远高于平均
- 缓存命中率按 key 分布：个别 key 命中率异常低（被频繁驱逐）

**缓存热点 key 的特殊问题：**

- **缓存击穿**：热点 key 过期瞬间，大量请求同时穿透到 DB。解决方案：互斥锁（singleflight）、永不过期 + 异步刷新、逻辑过期。
- **缓存雪崩**：大量 key 同时过期。解决方案：过期时间加随机偏移（TTL + random(0-300s)）。
- **惊群效应**：多个请求同时发现缓存未命中，同时去查 DB。解决方案：singleflight，同一 key 只允许一个请求穿透。

常见错误：
- 用随机后缀做写分片但读路径没做 scatter-gather
- 热点 key 缓存过期时间设成一样的，导致缓存击穿
- 只监控平均延迟，热点分片的延迟被平均值掩盖
- 把热点保护和限流混为一谈——热点保护是分散流量，限流是拒绝流量

面试里可以这样答：

```
热点保护分读热点和写热点。读热点用多级缓存 + singleflight 防击穿；写热点用写分片（加随机后缀）分散写入。Twitter 的混合 fan-out 是经典案例：普通用户预计算，大 V 实时拉取。检测手段是看 p50/p99 延迟差异和按分片的 QPS 分布。缓存热点 key 要防击穿（singleflight）和雪崩（TTL 加随机偏移）。
```

## Q015. 如何设计秒杀系统？

**回答：**

秒杀（Flash Sale / Seckill）的核心矛盾是：**数百万用户竞争极少量库存，且绝对不能超卖。** 解决方案不是"加机器"，而是"逐层削减流量"。

**四层漏斗架构：**

每一层把流量削减一个数量级：

```
Layer 1: CDN 等待室    10M -> 1M    （静态页面，不碰源站）
Layer 2: Token 闸门    1M -> 100K   （Redis 有序集合排队）
Layer 3: 原子库存      100K -> 1K   （Redis Lua 原子扣减）
Layer 4: 异步订单队列  1K -> 稳态写入（Kafka 缓冲，DB 慢消费）
```

**Layer 1：CDN 等待室**

- 纯静态 HTML/JS/CSS 放 CDN，倒计时在客户端运行
- T-0 时刻，JS 发起排队请求
- 吸收 10M+ 用户而不碰源站

**Layer 2：Token 闸门（虚拟队列）**

- Redis Sorted Set，score 用随机数（防止机器人优势）
- `ZADD waitroom:{sale_id} RANDOM_SCORE user_id`
- 分批放行：`ZPOPMIN waitroom:{sale_id} COUNT N`
- 放行用户获得有时限的 session token（如 30 分钟）

**Layer 3：原子库存（Redis + Lua）**

这是防止超卖的核心。Redis Lua 脚本保证原子性：

```lua
-- 原子扣减库存
local stock = redis.call('GET', KEYS[1])
if not stock or tonumber(stock) <= 0 then
    return -1  -- 已售罄
end
-- 检查用户是否已购买（防重复）
local bought = redis.call('SISMEMBER', KEYS[2], ARGV[1])
if bought == 1 then
    return -2  -- 已购买
end
redis.call('DECR', KEYS[1])
redis.call('SADD', KEYS[2], ARGV[1])
return redis.call('GET', KEYS[1])
```

Redis 单线程事件循环保证了这段 Lua 脚本的原子性，不会出现两个请求同时读到"还有 1 件"然后都扣减成功的情况。

**Layer 4：异步订单队列（Kafka）**

- 通过库存检查的用户获得订单预授权（order reference）
- 下单请求放入 Kafka 队列
- Worker 按可持续速率消费（如 1,000 订单/秒）
- 背压控制：队列堆积时减少 Token 闸门的放行速率

**防超卖的四种模式对比：**

| 模式 | 原理 | 代价 |
|------|------|------|
| DB 乐观锁 | `UPDATE SET qty=qty-1 WHERE qty>0` | 大流量下 DB 成为瓶颈 |
| Redis 原子 DECR | Lua 脚本，单线程 | 单商品热 key |
| 队列串行化 | 所有请求过单一队列 | 吞吐受限 |
| 按 Region 预分配 | 库存拆分到各 Region | 区域间库存不平衡 |

**防机器人：**

- CDN 层 WAF + 自定义规则
- 每 IP 限流
- 可疑流量弹验证码
- 设备指纹识别

**秒杀系统的关键设计决策：**

1. **库存事实来源**：Redis 是秒杀期间的实时库存，DB 是最终事实来源。秒杀结束后，Redis 库存同步回 DB。
2. **超时释放**：拿到 Token 但未在 N 分钟内下单的用户，Token 过期，库存回补。
3. **降级预案**：Redis 挂了怎么办？fail open（允许请求但做本地保守限流）还是 fail closed（拒绝所有请求）？秒杀场景通常 fail closed 更安全——宁可少卖，不能超卖。
4. **预热**：秒杀开始前，把库存加载到 Redis，把静态资源推到 CDN。

常见错误：
- 直接用 DB 做库存扣减——大流量下 DB 是最大瓶颈
- Redis 扣减不是原子的（先 GET 再 SET）——必超卖
- 没有虚拟队列，所有请求直接打到库存扣减——Redis 也扛不住
- 没有防重复购买检查——同一用户买多次

面试里可以这样答：

```
秒杀系统用四层漏斗：CDN 等待室（静态页面）-> Redis Token 闸门（有序集合排队）-> Redis Lua 原子库存扣减 -> Kafka 异步下单。核心是 Redis Lua 脚本保证原子扣减，绝不超卖。每一层削减一个数量级的流量，而不是靠加机器硬扛。降级策略是 fail closed——宁可少卖，不能超卖。
```

## Q016. 如何设计短链接系统？

**回答：**

短链接系统本质上是一个**伪装成存储问题的读密集型缓存问题**。读写比约 100:1，所以缓存是核心，存储是次要的。

**核心指标：**

| 指标 | 值 |
|------|-----|
| 读写比 | 100:1 |
| 短码长度 | 7 位（Base62） |
| 总可能短码数 | 62^7 = 3.5 万亿 |
| 重定向延迟目标 | p99 < 10ms（服务端） |

**短码生成（三种方案）：**

**方案一：Hash + 碰撞检测**

- 对长 URL 做 MD5/SHA256，取前 7 位
- 查 DB 检查碰撞，碰撞则重试
- 优点：无需协调
- 缺点：每次写入都要查 DB，大规模下有生日悖论碰撞

**方案二：Range-Based ID（Flickr Ticket Server 模式）**

- 预分配 ID 范围给每台服务器
- 服务器用 `UPDATE id_ranges SET next_range = next_range + 1000` 申领范围
- 本地计数器生成 1000 个 ID，转 Base62
- 优点：零协调写入，无碰撞
- 缺点：需要 ZooKeeper/DB 管理范围分配

**方案三：Snowflake 风格 ID**

- 时间戳 + worker ID + 序列号
- 转 Base62
- 优点：全局唯一，无协调
- 缺点：时钟回拨问题

**推荐方案二**，因为短链接的写入量不大（每天 100M），Range-Based ID 的简单性和无碰撞特性最适合。

**架构设计：**

```
写路径：Client -> Create Service -> Range ID Generator -> DB -> Cache (Redis)
读路径：Client -> CDN -> Redirect Service -> L1 LRU -> L2 Redis -> L3 DB -> 302
分析路径（异步）：Redirect Service -> Kafka -> Flink -> ClickHouse
```

**301 vs 302 重定向：**

| 状态码 | 浏览器行为 | 点击统计 | 链接撤销 |
|--------|-----------|---------|---------|
| 301 | 浏览器永久缓存 | 首次后丢失 | 需要数周才能生效 |
| 302 | 每次点击都请求服务器 | 精确 | 即时生效 |
| 301 + max-age=90 | 缓存 90 秒 | ~90 秒延迟 | ~90 秒延迟 |

Bitly 使用 301 + `Cache-Control: private, max-age=90`，在统计精度和性能之间取平衡。

**缓存策略：**

- L1：进程内 LRU（singleflight 防惊群）
- L2：Redis 集群（每 Region ~150M 条目）
- L3：DB（ScyllaDB/DynamoDB，RF=3）

**多 Region 部署：**

- 各 Region 独立 ID 生成（无需跨 Region 协调）
- ScyllaDB NetworkTopologyStrategy 做跨 DC 复制
- Anycast DNS 把用户路由到最近 Region

**短码字符集选择：**

Base62（0-9, a-z, A-Z）是最常见选择。避免使用容易混淆的字符（如 0/O、1/l/I）。7 位 Base62 = 3.5 万亿种组合，足够用几十年。

常见错误：
- 短码生成用全局自增 ID——单点瓶颈
- 读路径每次都查 DB——p99 延迟不可控
- 用 301 永久重定向——点击统计丢失
- 缓存没有 singleflight——热点短链接过期时惊群

面试里可以这样答：

```
短链接核心是读密集型缓存问题。写路径用 Range-Based ID 生成（Flickr 模式），零协调无碰撞。读路径用三级缓存（本地 LRU + Redis + DB），singleflight 防惊群。重定向用 301 + max-age=90 平衡性能和统计精度。分析走异步 Kafka -> Flink -> ClickHouse，不污染核心读写路径。
```

