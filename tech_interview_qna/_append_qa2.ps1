## Q005. 容量规划需要考虑峰值还是平均值？

**回答：**

两个都要看，但用途不同。**平均值用于成本估算，峰值用于容量规划。** 面试里如果只说"按峰值规划"，没有说清楚为什么、以及峰值怎么取，会被追问。

**为什么不能按平均值规划：**

平均 QPS 掩盖了流量波动。一个日活 100M 的系统，平均 QPS 可能是 12K，但晚高峰可能是 36K，突发新闻事件可能是 120K。如果按 12K 部署，晚高峰用户就会遇到超时和 5xx。排队论也告诉我们：当利用率超过 60%-80%，延迟会急剧上升。按平均值规划意味着系统在峰值时利用率远超安全阈值。

**为什么不能无脑按最大峰值规划：**

成本太高。一个峰值因子 10x 的系统，如果全部按峰值常驻部署，90% 的时间资源闲置。工程上需要在"够用"和"不浪费"之间找平衡。

**峰值因子的取值：**

| 流量模式 | 峰值/平均比 | 典型场景 |
|---------|-----------|---------|
| 平稳型 | 1.5-2x | 企业内部系统、B2B SaaS |
| 日周期型 | 2-5x | 社交媒体、新闻、电商 |
| 事件驱动型 | 10-100x | 秒杀、赛事直播、抢票 |
| 病毒传播型 | 100-1000x | 突发热点、名人动态 |

**容量规划的完整框架：**

1. **基线容量**：按平均 QPS 的 1.5-2x 部署常驻资源，覆盖日常波动
2. **弹性容量**：用自动扩缩容（HPA、Cluster Autoscaler）应对日周期峰值，峰谷时缩容省钱
3. **缓冲容量**：预留 N+2 冗余，覆盖计划内升级和单点故障
4. **降级容量**：极端峰值（如秒杀）不靠无限扩容，而是用排队、限流、降级来保护核心链路

**The Cost of Nines（可用性成本）：**

| 可用性 | 年宕机时间 | 相对成本 |
|--------|-----------|---------|
| 99% | 3.65 天 | 1x |
| 99.9% | 8.76 小时 | ~2x |
| 99.99% | 52.56 分钟 | ~10x |
| 99.999% | 5.26 分钟 | ~100x |

每多一个九，工程成本大约翻 10 倍。Google SRE Book 建议用 error budget 来平衡可靠性和发布速度：如果 error budget 没花完，可以继续发布；花完了就冻结发布，直到可靠性恢复。

常见错误：
- 只用平均值做容量规划，峰值时系统崩溃
- 全部按最大峰值常驻部署，成本浪费严重
- 不考虑弹性扩缩容的冷启动延迟（容器启动 + 健康检查 + 预热可能需要 30-120 秒）
- 忽略 error budget 概念，把"100% 可用"当成目标而不是"足够好"

## Q006. 如何设计横向扩展？

**回答：**

横向扩展（Horizontal Scaling）是通过增加机器数量来提升系统容量，与之相对的是纵向扩展（Vertical Scaling，换更大的机器）。面试里要能说清楚什么时候横向、什么时候纵向、以及横向扩展的前提条件。

**纵向 vs 横向对比：**

| 维度 | 纵向扩展 | 横向扩展 |
|------|---------|---------|
| 方式 | 换更大的机器 | 加更多机器 |
| 应用改动 | 无 | 需要无状态设计、分片 |
| 成本曲线 | 指数级（大机器很贵） | 线性（加普通机器） |
| 上限 | 受最大单机规格限制 | 理论上无上限 |
| 停机 | 通常需要重启 | 可以零停机扩容 |
| 复杂度 | 低 | 中到高 |

**横向扩展的前提：无状态设计。**

任何一个实例都能处理任何一个请求。需要避免的状态泄漏模式：
- 内存中的 session 数据 -> 放 Redis
- 本地文件存储 -> 放 S3/对象存储
- 粘性会话（sticky session）-> 把状态外化到共享缓存
- 本地缓存不一致 -> 用分布式缓存或最终一致性容忍

**扩展优先级（从便宜到贵）：**

| 层级 | 手段 | 复杂度 | 成本 |
|------|------|--------|------|
| 1 | 优化代码（修 N+1、加索引、减少序列化） | 低 | $0 |
| 2 | 加缓存（吸收 80-95% 读流量） | 低 | $ |
| 3 | 纵向扩展（换更大机器） | 无 | $$ |
| 4 | 读副本（读写分离） | 中 | $$ |
| 5 | CDN（静态内容边缘分发） | 低 | $ |
| 6 | 横向扩展应用层 | 中 | $$ |
| 7 | 数据库分片（最后手段） | 高 | $$$$ |

**Amdahl 定律在系统设计中的应用：**

```
加速比 = 1 / (1 - P)，其中 P = 可并行化的比例
如果 10% 的代码是串行的：最大加速比 = 1/0.10 = 10x
```

加 100 台机器，如果 10% 的逻辑必须串行（比如全局锁、单线程队列），系统最多快 10 倍。所以在横向扩展之前，先消除串行瓶颈。

**负载均衡算法选择：**

| 算法 | 适用场景 | 注意事项 |
|------|---------|---------|
| 轮询（Round Robin） | 均匀负载 | 不感知实际负载 |
| 最少连接（Least Connections） | 长连接、变长处理 | 需要追踪连接状态 |
| 一致性哈希 | 缓存、有状态路由 | 节点增减时重分布少 |
| 加权（Weighted） | 异构服务器 | 需要手动调权重 |

**自动扩缩容（HPA）的注意事项：**

Kubernetes HPA 基于 CPU/内存指标做扩缩容，但有几个坑：
- 冷启动延迟：容器启动 + 健康检查 + 预热可能需要 30-120 秒，突发流量来临时来不及扩容
- 抖动：指标在阈值附近波动会导致频繁扩缩容，需要设置 stabilizationWindowSeconds
- 指标选择：CPU 高不代表需要扩容（可能是死循环），QPS 高但 CPU 低也不需要扩容
- 建议用自定义指标（如 QPS、队列深度）而不是只用 CPU

面试里可以这样答：

```
横向扩展的前提是无状态设计。我会先确保应用层不持有本地状态（session 放 Redis，文件放对象存储），然后用负载均衡器分发流量。扩容策略上，先优化代码和加缓存（成本最低），再考虑横向扩展应用层，数据库分片是最后手段。自动扩缩容要配置冷启动预热和稳定窗口，避免突发流量打进来时来不及扩容。
```

## Q007. 如何发现系统中的单点瓶颈？

**回答：**

瓶颈（Bottleneck）是限制系统吞吐的组件，单点故障（SPOF）是挂了会导致全系统不可用的组件。两者经常重叠，但不是一回事。一个组件可以是瓶颈但不是 SPOF（比如有多个读副本但都慢），也可以是 SPOF 但不是瓶颈（比如一个轻量级但唯一的配置服务）。

**瓶颈识别框架：**

沿着一个用户请求的完整链路，在每个环节问五个问题：

1. **CPU 瓶颈？** —— 重计算、序列化/反序列化、加密、压缩
2. **内存瓶颈？** —— 缓存未命中、大对象、GC 压力、内存泄漏
3. **I/O 瓶颈？** —— 磁盘读写、网络调用、外部 API
4. **连接瓶颈？** —— DB 连接池耗尽、文件描述符上限、端口耗尽
5. **竞争瓶颈？** —— 锁竞争、全局互斥、单线程队列

**常见瓶颈排行榜（按出现频率）：**

| 瓶颈 | 症状 | 诊断手段 |
|------|------|---------|
| DB 连接池耗尽 | 连接超时、请求排队 | 连接池 metrics |
| 热点 key/分区 | 延迟不均，个别节点慢 | 按分片/节点看延迟 |
| 同步外部调用无超时 | 级联故障、线程耗尽 | 分布式追踪 |
| 单节点磁盘 I/O | fsync 慢、写入延迟高 | 磁盘延迟、iostat |
| 单线程代码路径 | 一个核 100%，其他核空闲 | 火焰图 |
| 全局锁 | 吞吐不随实例数线性增长 | 锁等待时间 |

**SPOF 消除清单：**

- 应用层：至少 2 个实例，放负载均衡器后面
- 负载均衡器：至少 2 个（active-passive 或 active-active），用多个 DNS 记录
- 数据库：主从 + 自动故障转移（RDS Multi-AZ、Patroni + etcd）
- 缓存：Redis Cluster 或 Sentinel，至少 3 节点
- 消息队列：Kafka 多 broker + RF=3
- DNS：多个 DNS 提供商
- 网络：多 AZ 部署，跨 AZ 的负载均衡

**Amdahl 定律的实战应用：**

如果加机器后吞吐不线性增长，说明有串行瓶颈。排查方向：
- 数据库连接池是否成为全局互斥点
- 是否有全局锁或单线程队列
- 是否有共享状态的竞争（如 Redis 热 key）
- 下游服务是否成为瓶颈（比如所有实例都调同一个慢 API）

**利用率的"拐点"：**

根据排队论，利用率超过 60%-80% 后，延迟会急剧上升。所以监控利用率比监控绝对 QPS 更有意义。如果一个组件的利用率持续超过 70%，它就是当前瓶颈，即使还没挂。

面试里可以这样答：

```
我会沿着请求链路逐层排查：先看 CPU、内存、I/O、连接数、锁竞争五个维度。常见瓶颈是 DB 连接池耗尽、热点分片、同步外部调用无超时。SPOF 消除要保证每一层至少有两个实例。如果加机器后吞吐不线性增长，说明有串行瓶颈，需要用火焰图和分布式追踪定位。
```

## Q008. 高可用设计中的故障域是什么？

**回答：**

故障域（Fault Domain）是一组共享同一个故障点的组件。当这个故障点出问题时，域内所有组件都会受影响。高可用设计的核心思想就是：**把鸡蛋放在不同的篮子里，并确保每个篮子不会同时被打翻。**

**故障域层级（从大到小）：**

| 故障域 | 范围 | 故障示例 | 隔离手段 |
|--------|------|---------|---------|
| 进程 | 单个进程 | Crash、OOM、死锁 | 多进程、supervisor 自动重启 |
| 主机 | 单台物理机/VM | 硬件故障、内核 panic、掉电 | 多实例跨主机部署 |
| 机架 | 一个机架 | 交换机故障、电源分配故障 | 跨机架部署 |
| 可用区（AZ） | 数据中心集群 | 冷却故障、电网问题、火灾/水灾 | 多 AZ 部署 |
| 区域（Region） | 地理区域 | 地震、区域网络中断 | 多 Region 部署 |
| 云提供商 | 整个云平台 | 控制面故障（罕见） | 多云（成本极高） |

**Bulkhead（隔舱）架构：**

AWS Well-Architected Framework 把故障隔离类比为船舱的隔舱设计——一个舱进水不会沉船。在软件系统中，这意味着：

- **Cell-based 架构**：每个"cell"是完整技术栈的独立部署。一个 cell 的故障不影响其他 cell。Amazon、Netflix 等大规模 SaaS 都在用。
- **连接池隔离**：不同下游服务用独立的连接池，一个慢服务不会耗尽所有连接。
- **线程池隔离**：核心路径和非核心路径用不同的线程池，非核心路径的线程耗尽不影响核心路径。

**Shuffle Sharding（混洗分片）：**

每个请求被分配到实例的一个子集（比如 100 个实例中选 3 个）。一个实例故障只影响被分片到它的请求，而不是所有请求。这比传统的"所有请求都可能打到任何实例"大大缩小了爆炸半径。AWS Route 53、Lambda 等服务内部都在用这个技术。

**Static Stability（静态稳定性）：**

设计系统使其在控制面完全不可用时仍能继续运行。比如：
- 负载均衡器的数据面和控制面分离：控制面挂了，已建立的连接继续工作
- 自动扩缩容挂了，已运行的实例继续服务
- 服务发现挂了，客户端用本地缓存的服务列表继续路由

**故障域的面试答题框架：**

1. 识别每一层的故障域
2. 确保关键组件跨故障域部署
3. 设计降级路径：当某个故障域不可用时，系统如何降级
4. 测试故障：定期做 Chaos Engineering，验证故障隔离是否真的有效

常见错误：
- 只在同一 AZ 内部署多个实例，以为这样就高可用了（一个 AZ 故障全挂）
- 控制面和数据面耦合：控制面挂了，数据面也停了
- 没有测试过故障切换，以为配置了多 AZ 就万事大吉
- 把"多实例"等同于"跨故障域"——同一机架上的 10 个实例共享同一个交换机

面试里可以这样答：

```
故障域是共享同一故障点的组件集合。高可用设计要逐层隔离：进程级（多进程）、主机级（多实例）、机架级（跨机架）、AZ 级（多 AZ）、Region 级（多 Region）。核心手段包括 Bulkhead 隔离、Shuffle Sharding 缩小爆炸半径、Static Stability 保证控制面挂了数据面还能跑。每一层都要实际测试过故障切换，不能只靠配置。
```

